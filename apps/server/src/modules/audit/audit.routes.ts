import { Router } from "express";
import { auditController } from "./audit.controller";
import { authenticate } from "#shared/middleware/authenticate";
import { authorize } from "#shared/middleware/authorize";
import { validate } from "#shared/middleware/validator";
import { registry } from "#shared/openapi/registry";
import {
  listAuditLogsQuerySchema,
  entityParamsSchema,
  actorParamsSchema,

  // success responses
  auditLogsListResponseSchema,
  auditEntityHistoryResponseSchema,
  auditActorHistoryResponseSchema,

  // error responses
  auditBadRequestResponse,
  auditUnauthorizedResponse,
  auditForbiddenResponse,
  invalidEntityParamsResponse,
  invalidActorIdResponse,
} from "./audit.schema";

export const auditRoutes = Router();

auditRoutes.use(authenticate, authorize("read", "AuditLog"));

// GET /audit
registry.registerPath({
  method: "get",
  path: "/audit",
  tags: ["Audit"],
  summary: "List audit logs",
  description: "Retrieves a filtered list of audit logs for system activities.",
  security: [{ bearerAuth: [] }],
  request: {
    query: listAuditLogsQuerySchema,
  },
  responses: {
    200: {
      description: "Audit logs retrieved successfully",
      content: { "application/json": { schema: auditLogsListResponseSchema } },
    },
    400: {
      description: "Invalid query parameters",
      content: {
        "application/json": {
          schema: auditBadRequestResponse,
        },
      },
    },
    401: {
      description: "Unauthorized",
      content: {
        "application/json": {
          schema: auditUnauthorizedResponse,
        },
      },
    },
    403: {
      description: "Forbidden",
      content: {
        "application/json": {
          schema: auditForbiddenResponse,
        },
      },
    },
  },
});

auditRoutes.get(
  "/",
  validate({ query: listAuditLogsQuerySchema }),
  auditController.list,
);

// GET /audit/entity/:entityType/:entityId
registry.registerPath({
  method: "get",
  path: "/audit/entity/{entityType}/{entityId}",
  tags: ["Audit"],
  summary: "Get logs by entity",
  description:
    "Retrieves all audit logs associated with a specific system entity.",
  security: [{ bearerAuth: [] }],
  request: {
    params: entityParamsSchema,
  },
  responses: {
    200: {
      description: "Entity logs retrieved successfully",
      content: {
        "application/json": { schema: auditEntityHistoryResponseSchema },
      },
    },
    400: {
      description: "Invalid entity parameters",
      content: { "application/json": { schema: invalidEntityParamsResponse } },
    },
    401: {
      description: "Unauthorized",
      content: {
        "application/json": {
          schema: auditUnauthorizedResponse,
        },
      },
    },
    403: {
      description: "Forbidden",
      content: {
        "application/json": {
          schema: auditForbiddenResponse,
        },
      },
    },
  },
});

auditRoutes.get(
  "/entity/:entityType/:entityId",
  validate({ params: entityParamsSchema }),
  auditController.getByEntity,
);

// GET /audit/actor/:actorUserId
registry.registerPath({
  method: "get",
  path: "/audit/actor/{actorUserId}",
  tags: ["Audit"],
  summary: "Get logs by actor",
  description: "Retrieves all audit logs generated by a specific staff member.",
  security: [{ bearerAuth: [] }],
  request: {
    params: actorParamsSchema,
  },
  responses: {
    200: {
      description: "Actor logs retrieved successfully",
      content: {
        "application/json": { schema: auditActorHistoryResponseSchema },
      },
    },
    400: {
      description: "Invalid actor ID",
      content: { "application/json": { schema: invalidActorIdResponse } },
    },
    401: {
      description: "Unauthorized",
      content: {
        "application/json": {
          schema: auditUnauthorizedResponse,
        },
      },
    },
    403: {
      description: "Forbidden",
      content: {
        "application/json": {
          schema: auditForbiddenResponse,
        },
      },
    },
  },
});

auditRoutes.get(
  "/actor/:actorUserId",
  validate({ params: actorParamsSchema }),
  auditController.getByActor,
);
